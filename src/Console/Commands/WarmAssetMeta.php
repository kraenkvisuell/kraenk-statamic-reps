<?php

namespace Kraenkvisuell\StatamicReps\Console\Commands;

use GuzzleHttp\Promise\Utils;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Filesystem\AwsS3V3Adapter;
use Statamic\Contracts\Assets\AssetContainer;
use Statamic\Facades\AssetContainer as AssetContainers;
use Statamic\Facades\YAML;
use Throwable;

/**
 * Loads the asset metadata (the .meta/*.yaml files next to the files) into Statamic's meta cache.
 * Every image a page renders needs its metadata; uncached that's one request to the disk (Bunny)
 * per image, which makes the first render of an artist page take minutes. On S3 disks the files
 * are fetched in parallel. Run it once on a new server or after clearing the asset_meta store.
 */
#[Signature('reps:warm-asset-meta {container? : Container handle (default: all)} {--concurrency=32 : Parallel requests on S3 disks} {--force : Reload metadata that is cached already}')]
#[Description('Load the metadata of all assets into the meta cache')]
class WarmAssetMeta extends Command
{
    public function handle(): int
    {
        if (! config('statamic.assets.cache_meta', true)) {
            $this->warn('statamic.assets.cache_meta is off, there is nothing to warm.');

            return self::SUCCESS;
        }

        $containers = $this->argument('container')
            ? collect([AssetContainers::findOrFail($this->argument('container'))])
            : AssetContainers::all();

        foreach ($containers as $container) {
            $this->warm($container);
        }

        return self::SUCCESS;
    }

    protected function warm(AssetContainer $container): void
    {
        $assets = $container->files()->map(fn ($path) => $container->makeAsset($path));
        $store = $assets->first()?->cacheStore();

        $missing = $this->option('force') ? $assets : $assets->reject(fn ($asset) => $store->has($asset->metaCacheKey()));

        $this->line(sprintf('%s: %d assets, %d to load', $container->handle(), $assets->count(), $missing->count()));

        if ($missing->isEmpty()) {
            return;
        }

        $disk = $container->disk()->filesystem();
        $bar = $this->output->createProgressBar($missing->count());
        $fallback = collect();

        if ($disk instanceof AwsS3V3Adapter) {
            $client = $disk->getClient();
            $bucket = $disk->getConfig()['bucket'];

            foreach ($missing->chunk(max(1, (int) $this->option('concurrency'))) as $chunk) {
                $results = Utils::settle($chunk->map(fn ($asset) => $client->getObjectAsync([
                    'Bucket' => $bucket,
                    'Key' => $disk->path($asset->metaPath()),
                ]))->all())->wait();

                foreach ($chunk as $index => $asset) {
                    $result = $results[$index];

                    try {
                        $meta = $result['state'] === 'fulfilled' ? YAML::parse((string) $result['value']['Body']) : null;
                    } catch (Throwable) {
                        $meta = null;
                    }

                    is_array($meta) ? $store->forever($asset->metaCacheKey(), $meta) : $fallback->push($asset);
                    $bar->advance();
                }
            }
        } else {
            $fallback = $missing;
        }

        // local disks, and assets without a readable .meta file: Statamic reads or generates it
        foreach ($fallback as $asset) {
            $store->forget($asset->metaCacheKey());
            $asset->meta();

            if (! $disk instanceof AwsS3V3Adapter) {
                $bar->advance();
            }
        }

        $bar->finish();
        $this->newLine();

        if ($disk instanceof AwsS3V3Adapter && $fallback->isNotEmpty()) {
            $this->line("  {$fallback->count()} without a readable .meta file, generated by Statamic");
        }
    }
}
